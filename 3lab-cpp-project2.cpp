#include <iostream>
#include <clocale>
using namespace std;

int main() {
	setlocale(LC_ALL, "ru");

    double a, b, c;

    std::cout << "Введите три стороны треугольника: ";

    // Считываем все три значения и проверяем успешность ввода.
    if (!(std::cin >> a >> b >> c)) {
        std::cout << "Ошибка: необходимо ввести три числа." << std::endl;

        return 1;
    }

    // Все стороны должны быть положительными, а каждое
    // неравенство треугольника должно выполняться одновременно.
    if (a > 0 && b > 0 && c > 0 && a < b + c && b < a + c && c < a + b) {

        std::cout << "Существует" << std::endl;
    }
    else {
        // Сюда попадут неположительные стороны или нарушенное
        // неравенство треугольника.
        std::cout << "Не существует" << std::endl;
    }

    return 0;
}
